from __future__ import annotations

from collections.abc import Callable, Coroutine
from typing import TYPE_CHECKING, Any, Protocol, runtime_checkable

if TYPE_CHECKING:
	import discord

EventHandler = Callable[[dict[str, Any]], Coroutine[Any, Any, None]]


@runtime_checkable
class StateStore(Protocol):
	"""Unified interface for caching guild state."""

	async def set_guild(self, guild_id: int, data: dict[str, Any]) -> None: ...

	async def get_guild(self, guild_id: int) -> dict[str, Any] | None: ...

	async def remove_guild(self, guild_id: int) -> None: ...

	async def set_channels(self, guild_id: int, channels: list[dict[str, Any]]) -> None: ...

	async def get_channels(self, guild_id: int) -> list[dict[str, Any]] | None: ...

	async def set_roles(self, guild_id: int, roles: list[dict[str, Any]]) -> None: ...

	async def get_roles(self, guild_id: int) -> list[dict[str, Any]] | None: ...

	async def add_bot_guild(self, guild_id: int) -> None: ...

	async def remove_bot_guild(self, guild_id: int) -> None: ...

	async def is_bot_guild(self, guild_id: int) -> bool: ...

	async def close(self) -> None: ...


@runtime_checkable
class EventBus(Protocol):
	"""Cross-container and in-process pub/sub event bus."""

	async def publish(self, channel: str, message: dict[str, Any]) -> None: ...

	async def subscribe(self, channel: str, handler: EventHandler) -> None: ...

	async def start(self) -> None: ...

	async def close(self) -> None: ...


@runtime_checkable
class MessageBuffer(Protocol):
	"""Buffer for compact message snapshots used in delete/edit audit logging."""

	def enqueue_message(self, message: discord.Message) -> None: ...

	async def get_message(self, channel_id: int, message_id: int) -> dict[str, Any] | None: ...

	async def start(self) -> None: ...

	async def close(self) -> None: ...


@runtime_checkable
class ShardCoordinator(Protocol):
	"""Coordinates shard assignment and leasing across bot clusters."""

	async def acquire_shards(self, total_shards: int, shards_per_cluster: int) -> list[int] | None: ...

	async def start_heartbeat(self) -> None: ...

	async def release_shards(self) -> None: ...

	async def update_health(self, shard_id: int, latency: float, guild_count: int, status: str) -> None: ...

	async def close(self) -> None: ...


@runtime_checkable
class SessionPersister(Protocol):
	"""Manages gateway session persistence for zero-blackout rolling restarts."""

	async def save_sessions(self, sessions: dict[int, dict[str, Any]]) -> None: ...

	async def get_session(self, shard_id: int) -> dict[str, Any] | None: ...

	async def clear_session(self, shard_id: int) -> None: ...

	async def acquire_identify_lock(self, shard_id: int, max_concurrency: int = 1) -> bool: ...

	async def release_identify_lock(self, shard_id: int, max_concurrency: int = 1) -> None: ...

	async def close(self) -> None: ...
